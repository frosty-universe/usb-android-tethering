#!/bin/sh
# Points the Homebrew tap at a published release: downloads the source tarball for a tag,
# computes its SHA-256 and writes Formula/usb-android-tethering.rb into a tap checkout.
#
#   scripts/brew/update-tap.sh vX.Y.Z            write the formula
#   scripts/brew/update-tap.sh --check vX.Y.Z    validate the formula already there, write nothing
#
# TAP_DIR defaults to a sibling checkout of the tap repository. --check runs `ruby -c` on the
# formula and confirms its sha256/url match the real release tarball; exit 1 on any mismatch.
set -eu

REPO="frosty-universe/usb-android-tethering"
TAP_DIR="${TAP_DIR:-$PWD/../homebrew-usb-android-tethering}"
FORMULA="Formula/usb-android-tethering.rb"

check=0
if [ "${1:-}" = "--check" ]; then
  check=1
  shift
fi
version=${1:?usage: update-tap.sh [--check] vX.Y.Z}
num=${version#v}
case $num in
  [0-9]*) ;;
  *) echo "version must look like v1.2.3, got '$version'" >&2; exit 2 ;;
esac
case $num in
  *..*|*[!0-9A-Za-z.-]*) echo "version must look like v1.2.3, got '$version'" >&2; exit 2 ;;
esac

[ -d "$TAP_DIR/.git" ] || { echo "tap checkout not found at $TAP_DIR (set TAP_DIR)" >&2; exit 1; }
formula="$TAP_DIR/$FORMULA"

if [ "$check" -eq 1 ]; then
  [ -f "$formula" ] || { echo "no formula at $formula" >&2; exit 1; }
  command -v ruby >/dev/null 2>&1 || { echo "ruby is required for --check" >&2; exit 1; }
  ruby -c "$formula" >/dev/null || { echo "$formula does not parse (ruby -c failed)" >&2; exit 1; }
  url=$(sed -n 's/^  url "\(.*\)"$/\1/p' "$formula")
  want=$(sed -n 's/^  sha256 "\(.*\)"$/\1/p' "$formula")
  [ -n "$url" ] || { echo "$formula has no url line" >&2; exit 1; }
  [ -n "$want" ] || { echo "$formula has no sha256 line" >&2; exit 1; }
  case $url in *"/$version.tar.gz") ;; *) echo "formula url is $url, expected tag $version" >&2; exit 1 ;; esac
  tmp=$(mktemp -d)
  trap 'rm -rf "$tmp"' EXIT
  trap 'exit 130' INT
  trap 'exit 143' TERM
  curl -fsSL --retry 3 -o "$tmp/src.tar.gz" "$url" \
    || { echo "could not download $url" >&2; exit 1; }
  got=$(shasum -a 256 "$tmp/src.tar.gz" | cut -d' ' -f1)
  [ "$got" = "$want" ] \
    || { echo "sha256 mismatch for $url" >&2; echo "  formula: $want" >&2; echo "  tarball: $got" >&2; exit 1; }
  echo "OK: $formula parses; $version sha256 $got matches"
  exit 0
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
url="https://github.com/$REPO/archive/refs/tags/$version.tar.gz"
curl -fsSL --retry 3 -o "$tmp/src.tar.gz" "$url" \
  || { echo "could not download $url (does tag $version exist?)" >&2; exit 1; }
sha=$(shasum -a 256 "$tmp/src.tar.gz" | cut -d' ' -f1)

mkdir -p "$TAP_DIR/Formula"
# Unquoted heredoc on purpose: $REPO, $version, $sha and $(date) are substituted by the shell,
# while #{...} belongs to Ruby and is passed through untouched. Backticks would run as command
# substitution, so the formula must not contain any.
cat > "$formula.tmp" <<EOF
# Generated by scripts/brew/update-tap.sh on $(date -u +%Y-%m-%dT%H:%MZ). Do not edit by hand.
class UsbAndroidTethering < Formula
  desc "Android USB tethering for macOS as a real Ethernet adapter"
  homepage "https://frosty-universe.github.io/usb-android-tethering/"
  url "https://github.com/$REPO/archive/refs/tags/$version.tar.gz"
  sha256 "$sha"
  license any_of: ["MIT", "Apache-2.0"]

  depends_on "rust" => :build
  depends_on :macos

  def install
    system "cargo", "install", *std_cargo_args
  end

  # The tether must run as root and owns its launchd job, so "brew services" is not the way to
  # start it: sudo usb-android-tethering install writes the daemon plist and network service.
  def caveats
    <<~EOS
      Finish the install (needs root for the launchd daemon and network service):

        sudo usb-android-tethering install
        usb-android-tethering status

      Then enable USB tethering on the phone. Remove everything with:

        sudo usb-android-tethering uninstall --purge
    EOS
  end

  test do
    assert_match "usb-android-tethering #{version}", shell_output("#{bin}/usb-android-tethering --version")
    system bin/"usb-android-tethering", "--help"
  end
end
EOF

# Cheap guard: the unquoted heredoc above lets the shell touch the Ruby, so make sure the
# result still parses (ruby ships with macOS and the runner image). Only then replace the
# live formula, so a broken one is never left in the tap.
if command -v ruby >/dev/null 2>&1; then
  ruby -c "$formula.tmp" >/dev/null \
    || { rm -f "$formula.tmp"; echo "$formula does not parse (ruby -c failed)" >&2; exit 1; }
fi
mv "$formula.tmp" "$formula"
echo "wrote $formula for $version (sha256 $sha)"
